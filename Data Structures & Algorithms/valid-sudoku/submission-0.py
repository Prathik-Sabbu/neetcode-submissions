class Solution:
    def isValidSudoku(self, board: List[List[str]]) -> bool:
        box = {0:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               1:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               2:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               3:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               4:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               5:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               6:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               7:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1},
               8:{"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1}}

        for column in board:
            rows = {"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1}
            for row in column:
                if row in rows:
                    rows[row] -= 1
                    if rows[row] < 0:
                        return False

        for i in range(9):
            col = {"1":1, "2":1, "3":1, "4":1, "5":1, "6":1, "7":1, "8":1, "9":1}
            for column in board:
                if column[i] in col:
                    col[column[i]] -= 1
                    if col[column[i]] < 0:
                        return False

        for i in range(9):
            for j in range(9):
                if board[i][j] in box[((int(i/3)*3) + int(j/3))]:
                    box[((int(i/3)*3) + int(j/3))][board[i][j]] -= 1
                    if box[((int(i/3)*3) + int(j/3))][board[i][j]] < 0:
                        return False
        return True

